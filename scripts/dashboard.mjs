#!/usr/bin/env node
// Writes logic-fabric/dashboard.html: one page with every change of the workspace as a card and, for each change, its
// request, spec, plan (as tasks), tests, the sources of the artifacts it saved, build log, review and acceptance,
// cross-linked (a requirement to its tasks, tests and artifacts). It reads only the workspace's files, needs no
// network and no packages, and the page it writes is self-contained: open it in any browser. The file is generated,
// so it is added to logic-fabric/.gitignore; hooks/dashboard.mjs rewrites it after every turn that changed the
// workspace, once it exists.
//
//   node scripts/dashboard.mjs [--workspace <repository or logic-fabric folder>] [--out <file>] [--redact-emails]
import { appendFileSync, existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { basename, dirname, extname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { STAGES, findWorkspace, parseStatus, readEnvironments, sha256 } from '../hooks/workspace.mjs';

export const DASHBOARD = 'dashboard.html';

// Writes the dashboard of a workspace (its logic-fabric folder); returns where, and how many changes it shows.
export function writeDashboard(workspace, { out, redactEmails = false } = {}) {
  const file = resolve(out || join(workspace, DASHBOARD));
  const template = readFileSync(join(dirname(fileURLToPath(import.meta.url)), 'dashboard.html'), 'utf8');
  const data = buildWorkspace(workspace);
  let json = JSON.stringify(data);

  // For a copy to share outside the team: e-mail addresses keep only their domain.
  if (redactEmails) {
    json = json.replace(/[\w.+-]+@([\w-]+\.)+[a-z]{2,}/gi, m => `•••@${m.split('@')[1]}`);
  }

  // The data sits in a JSON script block: "</" can't appear inside it, or it would end the block.
  const title = (data.project ? `${data.project} changes` : 'Logic Fabric changes').replace(/[<&]/g, '');
  const page = template
    .replace('<title>Logic Fabric changes</title>', () => `<title>${title}</title>`)
    .replace('/*__DATA__*/{}', () => json.replace(/<\//g, '<\\/'));
  writeFileSync(file, page);

  if (dirname(file) === resolve(workspace)) {
    ignore(workspace, basename(file));
  }

  return { file, changes: data.changes.length, bytes: page.length };
}

// Whether anything in the workspace changed after the dashboard was written.
export function isStale(workspace, file = join(workspace, DASHBOARD)) {
  if (!existsSync(file)) return false;
  const written = statSync(file).mtimeMs;
  const skip = new Set([resolve(file), resolve(join(workspace, '.gitignore'))]);
  const newer = dir => list(dir).some(name => {
    const path = join(dir, name);
    if (skip.has(resolve(path))) return false;
    const info = statSync(path);
    return info.isDirectory() ? newer(path) : info.mtimeMs > written;
  });
  return newer(workspace);
}

// The dashboard is generated: logic-fabric/.gitignore keeps it out of git.
function ignore(workspace, name) {
  const file = join(workspace, '.gitignore');
  const text = read(file) || '';
  if (!text.split(/\r?\n/).some(line => line.trim().replace(/^\//, '') === name)) {
    appendFileSync(file, `${text && !text.endsWith('\n') ? '\n' : ''}# Generated by /logic-fabric-dataverse:dashboard\n${name}\n`);
  }
}

function main() {
  const args = process.argv.slice(2);
  const option = name => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : undefined; };
  const workspace = locate(option('--workspace'));

  if (!workspace) {
    console.error('No Logic Fabric workspace (logic-fabric/workspace.yaml) here or above. Pass --workspace <folder>.');
    process.exit(1);
  }

  const result = writeDashboard(workspace, { out: option('--out'), redactEmails: args.includes('--redact-emails') });
  console.log(`Wrote ${result.file} (${result.changes} change${result.changes === 1 ? '' : 's'}, ${Math.round(result.bytes / 1024)} KB).`);
}

// ---------------------------------------------------------------------------------------------------------------
// The workspace

function locate(given) {
  if (given) {
    const dir = resolve(given);
    if (existsSync(join(dir, 'workspace.yaml'))) return dir;
    if (existsSync(join(dir, 'logic-fabric', 'workspace.yaml'))) return join(dir, 'logic-fabric');
    return null;
  }
  return findWorkspace(process.cwd());
}

function buildWorkspace(root) {
  const settings = parseStatus(read(join(root, 'workspace.yaml')) || '');
  const environments = Object.entries(readEnvironments(root)).map(([name, e]) => ({
    name, role: e.role || name, url: /^https:\/\/[^<>]+$/.test(e.url || '') ? e.url : null, testsAllowed: e.tests_allowed === 'true',
  }));
  const development = environments.find(e => e.role === 'development' && e.url)?.url || null;
  const active = (read(join(root, '.active')) || '').trim();
  const changesFolder = join(root, 'changes');
  const changes = existsSync(changesFolder)
    ? readdirSync(changesFolder).filter(n => statSync(join(changesFolder, n)).isDirectory())
      .map(id => buildChange(join(changesFolder, id), id, development))
      .sort((a, b) => b.id.localeCompare(a.id))
    : [];

  return {
    generatedAt: new Date().toISOString(),
    folder: relative(dirname(root), root) || 'logic-fabric',
    project: settings.project || null,
    solution: settings.solution || null,
    prefix: settings.prefix || null,
    offering: settings.offering || null,
    environments,
    active: changes.some(c => c.id === active) ? active : null,
    baselineTests: list(join(root, 'baseline', 'tests')).filter(f => /\.ya?ml$/i.test(f)).length,
    reports: readReports(join(root, 'reports')),
    stages: STAGES,
    changes,
  };
}

function readReports(folder) {
  const reports = [];
  for (const command of list(folder)) {
    for (const file of list(join(folder, command)).filter(f => f.endsWith('.md'))) {
      const text = read(join(folder, command, file));
      const doc = markdown(text);
      reports.push({ command, date: file.replace(/\.md$/, ''), title: firstHeading(text) || `${command} ${file}`, html: doc.html, toc: doc.toc });
    }
  }
  return reports.sort((a, b) => b.date.localeCompare(a.date));
}

// ---------------------------------------------------------------------------------------------------------------
// A change

function buildChange(folder, id, development) {
  const status = parseStatus(read(join(folder, 'status.yaml')) || '');
  const files = {
    request: 'request.md', spec: 'spec.md', plan: 'plan.md', buildLog: 'build-log.md',
    testReport: 'test-report.md', review: 'review.md', acceptance: 'acceptance.md',
  };
  const text = Object.fromEntries(Object.entries(files).map(([key, file]) => [key, read(join(folder, file))]));
  const quick = status.quick === 'true';
  const artifacts = readArtifacts(join(folder, 'artifacts'), development);
  const names = new Set(artifacts.map(a => a.name));
  const docs = {};

  for (const [key, value] of Object.entries(text)) {
    if (value !== null) {
      docs[key] = markdown(value, names);
    }
  }

  // A quick change has its tasks at the end of the spec.
  const tasks = parseTasks(text.plan ?? (quick ? text.spec : null) ?? '', names);
  const tests = readTests(join(folder, 'tests'));
  const report = text.testReport ? parseReport(text.testReport) : null;

  for (const test of tests) {
    test.result = report?.failed.has(test.id) ? 'failed' : report?.passed.has(test.id) ? 'passed' : null;
  }

  const review = text.review ? parseReview(text.review) : null;
  const stage = STAGES.includes(status.stage) ? status.stage : 'prompt';
  const approvals = {
    spec: approval(folder, status, 'spec'),
    plan: quick ? { ...approval(folder, status, 'spec'), quick: true } : approval(folder, status, 'plan'),
    accepted: status.accepted_by ? { by: status.accepted_by, at: status.accepted_at || null } : null,
    rejected: status.rejected_by ? { by: status.rejected_by, reason: status.rejected_reason || null } : null,
  };
  const findings = {
    blocker: num(status.findings_blocker), major: num(status.findings_major), minor: num(status.findings_minor),
  };
  const testRun = {
    total: num(status.tests_total) || report?.total || 0,
    passed: num(status.tests_passed) || report?.passedCount || 0,
    lastRun: status.tests_last_run || report?.run || null,
  };

  return {
    id,
    date: /^\d{4}-\d{2}-\d{2}/.exec(id)?.[0] || null,
    title: changeTitle(text) || id,
    owner: status.owner || null,
    stage,
    quick,
    approvals,
    findings,
    testRun,
    tasks,
    tests,
    report: report ? { run: report.run, total: report.total, passed: report.passedCount, failures: report.failures } : null,
    review: review ? { verdict: review.verdict, findings: review.findings } : null,
    artifacts,
    requirements: traceability(text.spec || '', tasks, tests, names),
    docs,
    updatedAt: latest(folder),
    attention: attention(stage, approvals, tasks, testRun, report, findings, review),
  };
}

function approval(folder, status, gate) {
  const by = status[`${gate}_approved_by`] || null;
  const at = status[`${gate}_approved_at`] || null;
  const recorded = (status[`${gate}_sha256`] || '').toLowerCase() || null;
  const now = sha256(join(folder, `${gate}.md`));
  const state = !by ? 'none' : now === null ? 'missing' : !recorded ? 'unverified' : now === recorded ? 'valid' : 'changed';
  return { by, at, state, fingerprint: recorded ? recorded.slice(0, 7) : null };
}

function attention(stage, approvals, tasks, testRun, report, findings, review) {
  const items = [];
  for (const gate of ['spec', 'plan']) {
    if (approvals[gate].state === 'changed' && !(gate === 'plan' && approvals.plan.quick)) {
      items.push({ level: 'bad', text: `${gate === 'spec' ? 'Spec' : 'Plan'} changed since it was approved` });
    }
  }
  const blocked = tasks.filter(t => t.blocked && !t.done).length;
  if (blocked) items.push({ level: 'warn', text: `${blocked} task${blocked > 1 ? 's' : ''} blocked` });
  const failing = report?.failures.length || (testRun.total && testRun.passed < testRun.total ? testRun.total - testRun.passed : 0);
  if (failing) items.push({ level: 'bad', text: `${failing} test${failing > 1 ? 's' : ''} failing` });
  const open = review?.findings.filter(f => /open/i.test(f.status) && /blocker|major/i.test(f.severity)).length
    ?? findings.blocker + findings.major;
  if (open && stage !== 'accepted') items.push({ level: 'bad', text: `${open} blocker or major finding${open > 1 ? 's' : ''} open` });
  if (stage === 'spec' && approvals.spec.state === 'none') items.push({ level: 'ask', text: 'Spec waiting for your approval' });
  if (stage === 'plan' && approvals.plan.state === 'none') items.push({ level: 'ask', text: 'Plan waiting for your approval' });
  if (stage === 'acceptance') items.push({ level: 'ask', text: 'Waiting for your acceptance' });
  return items;
}

function changeTitle(text) {
  for (const key of ['spec', 'request', 'plan']) {
    const heading = firstHeading(text[key] || '');
    if (heading) return heading.replace(/^(spec|request|build plan|plan)\s*:\s*/i, '');
  }
  return null;
}

// ---------------------------------------------------------------------------------------------------------------
// Plan tasks: "- [x] T-07 Create logic block `Name` (Formula)      REQ-3", then indented detail lines.

function parseTasks(text, names) {
  const tasks = [];
  let section = null;
  let inTasks = false;
  let current = null;

  for (const line of text.replace(/\r\n?/g, '\n').split('\n')) {
    const heading = /^(#{2,4})\s+(.*)$/.exec(line);
    if (heading) {
      if (heading[1] === '##') inTasks = /tasks/i.test(heading[2]);
      else if (inTasks) section = heading[2].trim();
      current = null;
      continue;
    }
    const task = /^\s{0,3}[-*] \[( |x|X)\] (T-\d+[a-z]?)\s+(.*?)\s*$/.exec(line);
    if (task) {
      const [, mark, id, rest] = task;
      const split = /^(.*?)\s{2,}(\S.*)$/.exec(rest);
      current = { id, title: (split ? split[1] : rest).trim(), ref: split ? split[2].trim() : null, done: mark !== ' ', section, lines: [] };
      tasks.push(current);
      continue;
    }
    if (current && /^\s+\S/.test(line)) {
      current.lines.push(line.trim());
    } else if (current && line.trim()) {
      current = null;
    }
  }

  return tasks.map(t => {
    const blockedLine = t.lines.find(l => /^(\*\*)?blocked\b/i.test(l));
    const body = t.lines.join('\n');
    return {
      id: t.id,
      title: inline(t.title, names),
      text: t.title.replace(/`/g, ''),
      ref: t.ref,
      reqs: [...new Set((t.ref || '').match(/REQ-\d+[a-z]?/g) || [])],
      section: t.section,
      done: t.done,
      blocked: Boolean(blockedLine),
      blockedReason: blockedLine ? blockedLine.replace(/^(\*\*)?blocked(\*\*)?:?\s*/i, '') : null,
      html: t.lines.length ? listBody(t.lines, names) : '',
      artifacts: [...new Set([...(t.title + '\n' + body).matchAll(/`([^`]+)`/g)].map(m => m[1]).filter(n => names.has(n)))],
      tests: [...new Set(body.match(/TC-\d+(?:\.\d+)?[a-z]?/g) || [])],
    };
  });
}

// Detail lines of a list item: a "Label:" line or a "- " sub-item starts a new line; anything else wraps on.
function listBody(lines, names) {
  return lines.map((l, i) => {
    if (i && /^-\s+/.test(l)) return `<br>• ${inline(l.replace(/^-\s+/, ''), names)}`;
    return (i && /^[A-Z][\w ()'/-]{0,30}:/.test(l) ? '<br>' : i ? ' ' : '') + inline(l, names);
  }).join('');
}

// ---------------------------------------------------------------------------------------------------------------
// Test cases: a few top-level fields read from the YAML (block or flow style); the source is shown as written.

function readTests(folder) {
  return list(folder).filter(f => /\.ya?ml$/i.test(f)).map(file => {
    const source = read(join(folder, file));
    const id = scalar(source, 'id') || file.replace(/\.ya?ml$/i, '');
    const target = mapping(source, 'target');
    const when = block(source, 'when');
    const expect = block(source, 'expect') || '';
    return {
      id,
      file,
      level: scalar(source, 'level'),
      covers: sequence(source, 'covers'),
      target: target.kind ? { kind: target.kind, name: target.name || null } : null,
      runAs: scalar(source, 'runAs'),
      retired: scalar(source, 'retired'),
      trigger: when ? (/\b(create|update|delete)\b/.exec(when)?.[1] || 'trigger') : null,
      expects: [...new Set([...expect.matchAll(/(?:^|[\s{,-])(output|error|records?|absent)\s*:/g)].map(m => m[1].replace(/^record$/, 'records')))],
      source,
    };
  }).sort((a, b) => naturalCompare(a.id, b.id));
}

function block(source, key) {
  const lines = source.replace(/\r\n?/g, '\n').split('\n');
  const start = lines.findIndex(l => new RegExp(`^${key}:`).test(l));
  if (start < 0) return null;
  const body = [lines[start].slice(key.length + 1)];
  for (let i = start + 1; i < lines.length && (/^\s/.test(lines[i]) || !lines[i].trim() || /^-\s/.test(lines[i])); i++) {
    body.push(lines[i]);
  }
  return body.join('\n');
}

function scalar(source, key) {
  const m = new RegExp(`^${key}:[ \\t]*(.+?)\\s*(#.*)?$`, 'm').exec(source);
  return m ? m[1].replace(/^["']|["']$/g, '') : null;
}

function sequence(source, key) {
  const value = block(source, key);
  if (!value) return [];
  const flow = /^\s*\[(.*)\]/.exec(value);
  const items = flow ? flow[1].split(',') : [...value.matchAll(/^\s*-\s*(.+)$/gm)].map(m => m[1]);
  return items.map(s => s.trim().replace(/^["']|["']$/g, '')).filter(Boolean);
}

function mapping(source, key) {
  const value = block(source, key);
  const result = {};
  if (!value) return result;
  for (const m of value.matchAll(/(\w+)\s*:\s*([^,{}\n]+)/g)) {
    result[m[1]] = m[2].trim().replace(/^["']|["']$/g, '');
  }
  return result;
}

// ---------------------------------------------------------------------------------------------------------------
// Test report and review

function parseReport(text) {
  const run = /\*\*Run:\*\*\s*([^·\n]+)/.exec(text)?.[1].trim() || null;
  const result = /\*\*Result:\*\*\s*(\d+)\s*\/\s*(\d+)/.exec(text);
  const failures = tableAfter(text, /^##\s+Failures/m).map(r => ({ id: r[0], expected: r[1], actual: r[2], notes: r[3] || '' }))
    .filter(r => /TC-/.test(r.id));
  const failed = new Set(failures.map(f => /TC-[\w.-]+/.exec(f.id)?.[0]).filter(Boolean));
  const passed = new Set();
  for (const row of tableAfter(text, /^##\s+Traceability/m)) {
    if (/pass/i.test(row[3] || '')) {
      for (const id of (row[2] || '').match(/TC-\d+(?:\.\d+)?[a-z]?/g) || []) if (!failed.has(id)) passed.add(id);
    }
  }
  return { run, total: result ? Number(result[2]) : 0, passedCount: result ? Number(result[1]) : 0, failures, failed, passed };
}

function parseReview(text) {
  const rows = tableAfter(text, /^\|\s*ID\s*\|/m, true);
  return {
    verdict: /\*\*Verdict:\*\*\s*(.+)/.exec(text)?.[1].trim() || null,
    findings: rows.filter(r => /^F-\d+/.test(r[0])).map(r => ({
      id: r[0], severity: r[1], artifact: r[2].replace(/`/g, ''), path: r[3].replace(/`/g, ''), rule: r[4], finding: r[5], fix: r[6], status: r[7] || '',
    })),
  };
}

// The rows of the first table after a heading (or starting at a header row), without its header and separator.
function tableAfter(text, marker, headerIsMarker = false) {
  const lines = text.replace(/\r\n?/g, '\n').split('\n');
  let i = lines.findIndex(l => marker.test(l));
  if (i < 0) return [];
  if (!headerIsMarker) while (i < lines.length && !/^\s*\|/.test(lines[i])) i++;
  i += 2;
  const rows = [];
  for (; i < lines.length && /^\s*\|/.test(lines[i]); i++) rows.push(cells(lines[i]).map(c => c.trim()));
  return rows;
}

