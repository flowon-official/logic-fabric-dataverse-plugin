// Requirements: REQ-n headings in the spec, with the acceptance criteria (AC-n.x), tasks, tests and artifacts.

function traceability(spec, tasks, tests, names) {
  const requirements = [];
  for (const m of spec.matchAll(/^#{2,4}\s+(REQ-(\d+)[a-z]?)\s+(.*)$/gm)) {
    requirements.push({ id: m[1], number: m[2], title: m[3].trim() });
  }
  const criteria = [...new Set(spec.match(/\bAC-\d+\.\d+[a-z]?\b/g) || [])];
  // Each criterion's wording: the line that starts with its ID, and the lines under it up to a blank line.
  const wording = {};
  const lines = spec.replace(/\r\n?/g, '\n').split('\n');
  const starts = l => /^\s*(?:[-*]\s+)?\**(AC-\d+\.\d+[a-z]?)\**[:.]?\s+(.*)$/.exec(l);
  lines.forEach((line, i) => {
    const m = starts(line);
    if (!m || wording[m[1]]) return;
    const parts = [m[2]];
    for (let j = i + 1; j < lines.length && lines[j].trim() && !starts(lines[j]) && !/^#/.test(lines[j]); j++) parts.push(lines[j].trim());
    wording[m[1]] = parts.join(' ').replace(/`/g, '').replace(/\*\*/g, '').slice(0, 500);
  });
  return requirements.map(r => {
    const reqTasks = tasks.filter(t => t.reqs.includes(r.id));
    const acs = criteria.filter(a => a.split('-')[1].split('.')[0] === r.number).sort(naturalCompare);
    const reqTests = tests.filter(t => t.covers.some(c => acs.includes(c)));
    return {
      id: r.id,
      title: r.title,
      criteria: acs,
      wording: Object.fromEntries(acs.filter(a => wording[a]).map(a => [a, wording[a]])),
      tasks: reqTasks.map(t => t.id),
      tasksDone: reqTasks.filter(t => t.done).length,
      tests: reqTests.map(t => t.id),
      artifacts: [...new Set(reqTasks.flatMap(t => t.artifacts))].filter(n => names.has(n)),
    };
  });
}

// ---------------------------------------------------------------------------------------------------------------
// Artifacts: the sources the export hook wrote to artifacts/<kind>/, summarized by kind.

const ETN = { logicBlock: 'flwn_logicblock', logicFlow: 'flwn_logicflow' };
const BLOCK_TYPES = { 1: 'Formula', 2: 'Decision table', 3: 'Decision tree', 4: 'Validation', 5: 'Validation set' };
const TYPE_CODES = ['Boolean', 'DateTime', 'Decimal', 'Double', 'Currency', 'Row', 'Lookup', 'Float', 'Image', 'Integer', 'Choice', 'Text', 'ID'];
const FREQUENCY = { 1: 'minute', 2: 'hour', 3: 'day', 4: 'week', 5: 'month' };
const CACHE = { 1: 'Volatile', 2: 'Ephemeral', 3: 'Constant' };

function readArtifacts(folder, development) {
  if (!existsSync(folder)) return [];
  let created = [];
  let links = {};
  try { created = JSON.parse(read(join(folder, 'created.json')) || '[]'); } catch { created = []; }
  try { links = JSON.parse(read(join(folder, 'links.json')) || '{}'); } catch { links = {}; }
  const artifacts = [];

  for (const sub of list(folder).filter(n => statSync(join(folder, n)).isDirectory())) {
    for (const file of list(join(folder, sub)).filter(f => statSync(join(folder, sub, f)).isFile())) {
      const raw = read(join(folder, sub, file));
      const ext = extname(file).toLowerCase();
      if (ext === '.json') {
        let source;
        try { source = JSON.parse(raw); } catch { source = null; }
        if (source && typeof source === 'object') {
          artifacts.push(summarize(source, sub, file, created, links, development));
          continue;
        }
      }
      artifacts.push({
        kind: sub, group: sub === 'records' ? 'Reference data' : sub === 'security' ? 'Security' : 'Files',
        name: file, title: null, description: describeFile(sub, file), facts: [], io: null,
        language: ext === '.xml' ? 'xml' : ext === '.json' ? 'json' : 'text', source: raw, url: null, file: `${sub}/${file}`,
      });
    }
  }

  const order = ['Data model', 'Logic blocks', 'Logic flows', 'Recipes', 'Business processes', 'Events', 'Schedules', 'Configurations', 'Service connections', 'Projects', 'Reference data', 'Security', 'Files'];
  return artifacts.sort((a, b) => (order.indexOf(a.group) - order.indexOf(b.group)) || a.name.localeCompare(b.name));
}

function describeFile(sub, file) {
  if (sub === 'records') return 'Rows of reference data, for the Flowon command-line import.';
  if (sub === 'security') return 'Security roles and their privileges, for the Flowon command-line import.';
  return null;
}

function summarize(source, sub, file, created, links, development) {
  const kind = source.kind || sub;
  const metadata = typeof source.metadata === 'string' ? safeJson(source.metadata) : source.metadata;
  const def = metadata?.def || null;
  const facts = [];
  let io = null;
  let group = 'Files';
  let name = source.name || file.replace(/\.json$/, '');

  switch (kind) {
    case 'logicBlock':
      group = 'Logic blocks';
      facts.push(['Type', BLOCK_TYPES[source.logicBlockType] || String(source.logicBlockType ?? '')]);
      io = interfaceOf(def, def?.type ? { result: { type: def.type.typeCode || def.type.type, list: def.type.list } } : null);
      facts.push(['Precondition', precondition(def?.precondition)]);
      if (source.isAction) facts.push(['Dataverse action', 'Yes']);
      break;
    case 'logicFlow':
      group = 'Logic flows';
      io = interfaceOf(def);
      facts.push(['Steps', String(countSteps(def?.action))]);
      if (def?.dataFetchers && Object.keys(def.dataFetchers).length) facts.push(['Reads', Object.keys(def.dataFetchers).join(', ')]);
      facts.push(['Precondition', precondition(def?.precondition)]);
      if (source.isAction) facts.push(['Dataverse action', 'Yes']);
      break;
    case 'logicRecipe':
      group = 'Recipes';
      facts.push(['Table', def?.entity || source.entityLogicalName || '—']);
      facts.push(['Runs on', ['create', 'update', 'delete', 'assign', 'setState'].filter(e => def?.[e]).join(', ') || '—']);
      facts.push(['Enabled', source.disabled ? 'No' : 'Yes']);
      break;
    case 'businessProcess':
      group = 'Business processes';
      break;
    case 'eventDefinition': case 'eventHandler':
      group = 'Events';
      break;
    case 'schedule':
      group = 'Schedules';
      facts.push(['Runs', `every ${source.interval > 1 ? `${source.interval} ` : ''}${FREQUENCY[source.frequency] || 'period'}${source.interval > 1 ? 's' : ''}`]);
      if (source.startDate) facts.push(['From', source.startDate]);
      if (source.nextRunDate) facts.push(['Next run', source.nextRunDate]);
      break;
    case 'configuration':
      group = 'Configurations';
      facts.push(['Type', TYPE_CODES[source.type] || String(source.type ?? '')]);
      facts.push(['Value', String(source.value ?? '')]);
      facts.push(['Cache', `${CACHE[source.cacheEntryStrategy] || '—'}${source.timeToLive ? `, ${source.timeToLive} s` : ''}`]);
      break;
    case 'serviceConnection':
      group = 'Service connections';
      break;
    case 'project':
      group = 'Projects';
      if (source.solutionDetails) facts.push(['Solution', `${source.solutionDetails.UniqueName} (prefix ${source.solutionDetails.Prefix})`]);
      break;
    case 'table': case 'column': case 'choice': case 'relationship': {
      group = 'Data model';
      const d = source.definition || {};
      if (kind === 'column') name = `${source.table}.${source.name}`;
      facts.push(['Kind', kind[0].toUpperCase() + kind.slice(1)]);
      if (d.displayName) facts.push(['Display name', d.displayName]);
      if (kind === 'table') {
        facts.push(['Ownership', d.ownership || '—']);
        if (d.primaryName?.name) facts.push(['Primary name', d.primaryName.name]);
        if (d.features) facts.push(['Features', Object.entries(d.features).filter(([, v]) => v).map(([k]) => k).join(', ') || 'none']);
      }
      if (kind === 'column') {
        facts.push(['Type', d.type || '—']);
        if (d.required) facts.push(['Required', d.required]);
        if (d.min !== undefined || d.max !== undefined) facts.push(['Range', `${fmtNumber(d.min)} to ${fmtNumber(d.max)}`]);
        if (d.maxLength) facts.push(['Max length', String(d.maxLength)]);
        if (d.precision !== undefined) facts.push(['Precision', String(d.precision)]);
        if (d.target) facts.push(['Looks up', d.target]);
      }
      if (kind === 'choice' && Array.isArray(d.options)) {
        facts.push(['Values', d.options.map(o => `${o.value} ${o.label}`).join(' · ')]);
      }
      break;
    }
    default:
      break;
  }

  // The link Foundry returned when it saved the artifact (export hook), else one built from the ID of what the change
  // created, for changes exported before links were recorded.
  const record = created.find(c => c.kind === kind && c.name === source.name);
  const url = (/^https:\/\//.test(links[`${kind}:${name}`] || '') ? links[`${kind}:${name}`] : null)
    || (record?.id && ETN[kind] && development ? `${development}/main.aspx?pagetype=entityrecord&etn=${ETN[kind]}&id=${record.id}` : null);

  return {
    kind, group, name,
    // A column is listed by its own name, with its display name and table under it.
    label: kind === 'column' ? source.name : null,
    subtitle: kind === 'column' ? [source.definition?.displayName, source.table].filter(Boolean).join(' · ') : null,
    title: source.title || source.definition?.displayName || null,
    description: source.description || source.definition?.description || null,
    facts, io, url, created: Boolean(record),
    language: 'json', source: JSON.stringify(source, null, 2), file: `${sub}/${file}`,
  };
}

function interfaceOf(def, outputs) {
  if (!def) return null;
  const describe = map => Object.entries(map || {}).map(([name, a]) => ({
    name,
    type: typeName(a),
    required: a.required === true,
    description: a.metaInfo?.description || null,
  }));
  return { inputs: describe(def.input), outputs: describe(outputs || def.output) };
}

function typeName(a) {
  const type = { Money: 'Currency', EntityReference: 'Lookup', Entity: 'Row', OptionSet: 'Choice', String: 'Text' }[a.type] || a.type || '?';
  const of = a.entityLogicalName || a.optionSetLogicalName;
  return `${type}${of ? ` (${of})` : ''}${a.dateTimeBehavior === 'DateOnly' ? ' (date only)' : ''}${a.list ? ', list' : ''}`;
}

function precondition(p) {
  if (!p) return 'None';
  const parts = [];
  const policies = p.authorization?.policies || (p.authorization ? [p.authorization] : []);
  if (policies.length) parts.push(policies.map(x => x.type === 'hasRole' ? `role ${x.role || x.name || ''}`.trim() : x.type === 'hasPermission' ? `${x.access || ''} ${x.table || ''}`.trim() : x.type).join(p.authorization?.type === 'any' ? ' or ' : ' and '));
  if (p.condition) parts.push('a condition');
  return `${parts.join(', plus ') || 'Yes'}${p.code ? ` (else ${p.code})` : ''}`;
}

function countSteps(action) {
  let count = 0;
  const visit = node => {
    if (!node || typeof node !== 'object') return;
    if (Array.isArray(node)) { node.forEach(visit); return; }
    if (typeof node.type === 'string' && node.metaInfo !== undefined) count++;
    for (const [key, value] of Object.entries(node)) {
      if (['actions', 'true', 'false', 'try', 'catch', 'finally', 'cases', 'responses'].includes(key) || /^\d{3}$/.test(key)) visit(value);
      else if (value && typeof value === 'object' && !Array.isArray(value) && key !== 'metaInfo' && typeof value.type === 'string' && value.metaInfo !== undefined) visit(value);
    }
  };
  visit(action);
  return Math.max(0, count - 1);
}

