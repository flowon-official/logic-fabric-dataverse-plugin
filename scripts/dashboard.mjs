// Helpers

function read(file) {
  try { return existsSync(file) ? readFileSync(file, 'utf8').replace(/^﻿/, '') : null; } catch { return null; }
}

function list(folder) {
  try { return existsSync(folder) ? readdirSync(folder).sort() : []; } catch { return []; }
}

function latest(folder) {
  let newest = 0;
  const walk = dir => {
    for (const name of list(dir)) {
      const path = join(dir, name);
      const info = statSync(path);
      if (info.isDirectory()) walk(path);
      else newest = Math.max(newest, info.mtimeMs);
    }
  };
  walk(folder);
  return newest ? new Date(newest).toISOString() : null;
}

function firstHeading(text) {
  return /^#\s+(.+)$/m.exec(text || '')?.[1].trim() || null;
}

function esc(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function num(v) {
  const n = Number(v);
  return Number.isFinite(n) ? n : 0;
}

function fmtNumber(v) {
  return v === undefined || v === null ? '—' : Number(v).toLocaleString('en-US');
}

function safeJson(s) {
  try { return JSON.parse(s); } catch { return null; }
}

function naturalCompare(a, b) {
  return String(a).localeCompare(String(b), 'en', { numeric: true });
}

