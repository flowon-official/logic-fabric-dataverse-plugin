// Markdown (what the plugin writes: headings, paragraphs, lists with task boxes, tables, code, quotes, rules)

function markdown(text, names = new Set()) {
  const lines = String(text).replace(/\r\n?/g, '\n').split('\n');
  const html = [];
  const toc = [];
  const used = new Map();
  let i = 0;

  const anchor = raw => {
    const req = /^(REQ-\d+[a-z]?)\b/.exec(raw);
    let slug = req ? req[1].toLowerCase() : raw.toLowerCase().replace(/`/g, '').replace(/[^\w\- ]+/g, '').trim().replace(/\s+/g, '-') || 'section';
    const n = used.get(slug) || 0;
    used.set(slug, n + 1);
    return n ? `${slug}-${n}` : slug;
  };
  const startsBlock = l => /^(#{1,6})\s/.test(l) || /^\s*(```|~~~)/.test(l) || /^\s{0,3}([-*+]|\d+[.)])\s+/.test(l) || /^\s*\|/.test(l) || /^\s*>/.test(l) || /^\s{0,3}([-*_])(\s*\1){2,}\s*$/.test(l);

  while (i < lines.length) {
    const line = lines[i];
    let m;
    if (!line.trim()) { i++; continue; }

    if ((m = /^\s*(```|~~~)\s*([\w-]*)/.exec(line))) {
      const body = [];
      for (i++; i < lines.length && !lines[i].trim().startsWith(m[1]); i++) body.push(lines[i]);
      i++;
      html.push(`<pre class="code"><code>${esc(body.join('\n'))}</code></pre>`);
      continue;
    }
    if ((m = /^(#{1,6})\s+(.*?)\s*#*\s*$/.exec(line))) {
      const level = m[1].length;
      const id = anchor(m[2]);
      if (level > 1 && level < 4) toc.push({ level, text: m[2].replace(/`/g, ''), id });
      html.push(`<h${level} id="${id}">${inline(m[2], names)}</h${level}>`);
      i++;
      continue;
    }
    if (/^\s{0,3}([-*_])(\s*\1){2,}\s*$/.test(line)) { html.push('<hr>'); i++; continue; }
    if (/^\s*\|/.test(line) && i + 1 < lines.length && /^\s*\|?\s*:?-{2,}/.test(lines[i + 1])) {
      const head = cells(line);
      const rows = [];
      for (i += 2; i < lines.length && /^\s*\|/.test(lines[i]); i++) rows.push(cells(lines[i]));
      html.push(`<div class="table-wrap"><table>${columnWidths(head, rows)}<thead><tr>${head.map(c => `<th>${inline(c.trim(), names)}</th>`).join('')}</tr></thead><tbody>${rows.map(r => `<tr>${head.map((_, k) => `<td>${inline((r[k] || '').trim(), names)}</td>`).join('')}</tr>`).join('')}</tbody></table></div>`);
      continue;
    }
    if (/^\s*>/.test(line)) {
      const body = [];
      for (; i < lines.length && /^\s*>/.test(lines[i]); i++) body.push(lines[i].replace(/^\s*>\s?/, ''));
      html.push(`<blockquote>${markdown(body.join('\n'), names).html}</blockquote>`);
      continue;
    }
    if (/^\s{0,3}([-*+]|\d+[.)])\s+/.test(line)) {
      const block = [];
      for (; i < lines.length; i++) {
        const l = lines[i];
        if (!l.trim()) {
          const next = lines.slice(i + 1).find(x => x.trim());
          if (next && (/^\s+\S/.test(next) || /^\s{0,3}([-*+]|\d+[.)])\s+/.test(next))) { continue; }
          break;
        }
        if (block.length && !/^\s/.test(l) && !/^([-*+]|\d+[.)])\s+/.test(l)) break;
        block.push(l);
      }
      html.push(renderList(block, names));
      continue;
    }
    const para = [];
    for (; i < lines.length && lines[i].trim() && (!para.length || !startsBlock(lines[i])); i++) para.push(lines[i].trim());
    html.push(`<p>${inline(para.join(' '), names)}</p>`);
  }

  return { html: html.join('\n'), toc };
}

// Each column's share of a table's width, from how much text its cells hold on average (between 8 and 120
// characters), so a column of sentences, such as the build log's results, gets the room and short ones don't.
function columnWidths(head, rows) {
  if (head.length < 3) return '';
  const plain = c => String(c || '').replace(/`|\*\*/g, '').trim();
  const weights = head.map((h, k) => {
    const values = rows.map(r => plain(r[k])).filter(Boolean);
    const average = values.length ? values.reduce((sum, v) => sum + v.length, 0) / values.length : plain(h).length;
    return Math.min(120, Math.max(8, average, plain(h).length));
  });
  const total = weights.reduce((sum, w) => sum + w, 0);
  return `<colgroup>${weights.map(w => `<col style="width:${(100 * w / total).toFixed(1)}%">`).join('')}</colgroup>`;
}

function renderList(lines, names) {
  // Items with their indentation; lines without a marker continue the item above.
  const items = [];
  for (const line of lines) {
    const m = /^(\s*)([-*+]|\d+[.)])\s+(.*)$/.exec(line);
    if (m) items.push({ indent: m[1].length, ordered: /\d/.test(m[2]), lines: [m[3]] });
    else if (items.length) items[items.length - 1].lines.push(line.trim());
  }
  let i = 0;
  const build = indent => {
    const ordered = items[i]?.ordered;
    const parts = [];
    while (i < items.length && items[i].indent >= indent) {
      const item = items[i];
      if (item.indent > indent) { parts.push(build(item.indent)); continue; }
      i++;
      let first = item.lines[0];
      let box = '';
      const task = /^\[( |x|X)\]\s+(.*)$/.exec(first);
      if (task) { box = `<span class="box ${task[1] === ' ' ? 'open' : 'done'}" aria-label="${task[1] === ' ' ? 'Open' : 'Done'}"></span>`; first = task[2]; }
      let inner = box + listBody([first, ...item.lines.slice(1)], names);
      if (i < items.length && items[i].indent > indent) inner += build(items[i].indent);
      parts.push(`<li${box ? ' class="task"' : ''}>${inner}</li>`);
    }
    return `<${ordered ? 'ol' : 'ul'}>${parts.join('')}</${ordered ? 'ol' : 'ul'}>`;
  };
  const out = [];
  while (i < items.length) out.push(build(items[i].indent));
  return out.join('');
}

const REF = /\b(REQ-\d+[a-z]?|AC-\d+\.\d+[a-z]?|TC-\d+(?:\.\d+)?[a-z]?|T-\d+[a-z]?|F-\d+)\b/g;

function inline(source, names = new Set()) {
  const codes = [];
  let s = String(source).replace(/`([^`]+)`/g, (_, c) => `\u0000${codes.push(c) - 1}\u0000`);
  s = esc(s);
  s = s.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, label, url) => /^https?:\/\//i.test(url) ? `<a href="${url}" target="_blank" rel="noopener">${label}</a>` : label);
  s = s.replace(/\*\*([^*]+?)\*\*/g, '<strong>$1</strong>');
  s = s.replace(/(^|[^\w*])\*(?!\s)([^*]+?)\*(?!\w)/g, '$1<em>$2</em>');
  // Cross-references, outside links.
  let inLink = 0;
  s = s.split(/(<[^>]+>)/).map(part => {
    if (part.startsWith('<')) {
      if (/^<a\b/i.test(part)) inLink++;
      else if (/^<\/a>/i.test(part)) inLink = Math.max(0, inLink - 1);
      return part;
    }
    return inLink ? part : part.replace(REF, r => `<a class="ref" href="#" data-ref="${r}">${r}</a>`);
  }).join('');
  return s.replace(/\u0000(\d+)\u0000/g, (_, n) => {
    const code = codes[Number(n)];
    return names.has(code) ? `<a class="ref" href="#" data-artifact="${esc(code)}"><code>${esc(code)}</code></a>` : `<code>${esc(code)}</code>`;
  });
}

function cells(line) {
  const parts = [];
  let current = '';
  let code = false;
  const body = line.trim().replace(/^\|/, '').replace(/\|$/, '');
  for (let k = 0; k < body.length; k++) {
    const ch = body[k];
    if (ch === '\\' && body[k + 1] === '|') { current += '|'; k++; continue; }
    if (ch === '`') code = !code;
    if (ch === '|' && !code) { parts.push(current); current = ''; continue; }
    current += ch;
  }
  parts.push(current);
  return parts;
}

