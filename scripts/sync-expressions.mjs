#!/usr/bin/env node
// Writes the exact argument shape of every FoL expression into the logic-fabric-dataverse plugin's expressions
// reference, from the grammar Logic Foundry serves (fol-grammar.json in the flowon-xrm repository), so the plugin
// never guesses whether a function takes "arg" or "args".
//
//   node scripts/sync-expressions.mjs <path to fol-grammar.json>          rewrite the table
//   node scripts/sync-expressions.mjs <path to fol-grammar.json> --check  fail when the table is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const [grammarPath, flag] = process.argv.slice(2);

if (!grammarPath) {
  console.error('Usage: node scripts/sync-expressions.mjs <path to fol-grammar.json> [--check]');
  process.exit(2);
}

const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'skills', 'artifacts', 'reference', 'expressions.md');
const START = '<!-- functions:start (generated by scripts/sync-expressions.mjs; do not edit) -->';
const END = '<!-- functions:end -->';

const grammar = JSON.parse(readFileSync(grammarPath, 'utf8'));
const rows = [];

for (const [name, definition] of Object.entries(grammar.definitions ?? {})) {
  const type = definition?.properties?.type;
  const functions = type?.enum ?? (type?.const ? [type.const] : []);

  // Expressions only: flow actions, data fetchers and the like have their own references.
  if (!name.endsWith('Expression') || functions.length === 0) {
    continue;
  }

  rows.push({ functions, shape: shape(definition), about: about(definition.description) });
}

function shape(definition) {
  const properties = definition.properties ?? {};
  const required = new Set(definition.required ?? []);
  const keys = Object.keys(properties).filter(k => k !== 'type' && k !== 'metaInfo');
  const named = k => `\`${k}\`${required.has(k) ? '' : ' (optional)'}`;

  if (properties.args) {
    const { minItems: min = 0, maxItems: max } = properties.args;
    const count = max === undefined ? `${min} or more` : min === max ? `exactly ${min}` : `${min} to ${max}`;
    return [...keys.filter(k => k !== 'args').map(named), `\`args\`${required.has('args') ? '' : ' (optional)'}: a list, ${count}`].join(', ');
  }

  if (keys.length === 1 && keys[0] === 'arg') {
    return required.has('arg') ? '`arg`: one expression' : '`arg`: one expression, optional';
  }

  if (keys.length === 0) {
    return 'none';
  }

  return keys.map(named).join(', ');
}

// The grammar's description without its source-file references, on one line.
function about(text = '') {
  // "Source: A.cs, B.cs etc. — reads 'operator'" keeps "reads 'operator'": the files are for the server's
  // developers, the detail after them is for authors.
  return text
    .replace(/\s*Source:\s*(?:[\w.]+\.cs(?:\s*,\s*|\s+and\s+|\s+)?)+(?:etc\.?)?\s*(?:[—–-]\s*)?/g, ' ')
    .replace(/\s+([.,;])/g, '$1')
    .replace(/(\w)\.\.(?!\.)/g, '$1.')
    .replace(/\s+/g, ' ')
    .replace(/\|/g, '\\|')
    .trim();
}

rows.sort((a, b) => a.functions[0].localeCompare(b.functions[0]));

const table = [
  '| Functions | Arguments | What they do |',
  '|---|---|---|',
  ...rows.map(r => `| ${r.functions.map(f => `\`${f}\``).join(', ')} | ${r.shape} | ${r.about} |`),
].join('\n');

const page = readFileSync(target, 'utf8');
const start = page.indexOf(START);
const end = page.indexOf(END);

if (start < 0 || end < start) {
  console.error(`${target} has no ${START} ... ${END} markers.`);
  process.exit(2);
}

const next = `${page.slice(0, start + START.length)}\n${table}\n${page.slice(end)}`;

if (flag === '--check') {
  if (next !== page) {
    console.error('The expressions table is out of date: run node scripts/sync-expressions.mjs <fol-grammar.json>.');
    process.exit(1);
  }

  console.log(`The expressions table is up to date (${rows.length} rows).`);
} else {
  writeFileSync(target, next);
  console.log(`Wrote ${rows.length} rows to ${target}.`);
}
